"""Shared chart identity for the PyPortfolios research notes.

Every figure in every note is drawn through this module so the whole set reads
as one publication. The palette is not invented: it was sampled out of the
reference note's own figures (white ground, navy #1a2c5b primary, ochre
#c49a2c secondary, #e6e6e6 grid, #aaaaaa axes, #6b6b6b labels), and the
typeface is the document's own TeX Gyre Heros.

Chart data comes from the article's data module under
site/src/content/articles/data/ -- the same file the site's ECharts components
render, generated by the quant pipeline from real computed results. Nothing is
invented here; load_data() just reads those numbers.
"""
