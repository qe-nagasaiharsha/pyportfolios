def load_data(module):
    """Read a site data module (const data = {...} as const) as a dict."""
    path = os.path.join(DATA_DIR, module + ".ts")
    src = io.open(path, encoding="utf-8").read()
    m = re.search(r"const data\s*=\s*(\{.*?\})\s*(?:as const)?\s*;\s*"
                  r"(?:export default data)", src, re.S)
    if not m:
        raise ValueError("could not parse data module: %s" % path)
    return json.loads(m.group(1))


def style(ax, xgrid=False, ygrid=True):
    """House axis treatment: muted tick labels, horizontal rules only."""
    for lbl in ax.get_xticklabels() + ax.get_yticklabels():
        lbl.set_color(MUTED)
    ax.grid(axis="x", visible=xgrid)
    ax.grid(axis="y", visible=ygrid)


def finish(fig, outdir, name, pad=0.3):
    os.makedirs(outdir, exist_ok=True)
    fig.tight_layout(pad=pad)
    path = os.path.join(outdir, name)
    fig.savefig(path, dpi=DPI)
    plt.close(fig)
    return path


def figure(height):
    """A full-measure figure of the given height in inches."""
    return plt.subplots(figsize=(WIDTH, height))


def diverging():
    """Ochre - white - navy, for correlation matrices and other signed scales.

    Built from the house pair rather than a stock matplotlib map so heatmaps
    belong to the same publication as the line and bar charts. Zero sits on
    white, so sign reads instantly and magnitude reads as saturation.
    """
    from matplotlib.colors import LinearSegmentedColormap
    return LinearSegmentedColormap.from_list(
        "pq_diverging", [OCHRE, "#f2ece0", "#ffffff", "#c9d0dd", NAVY])


def sequential():
    """White - navy, for unsigned magnitude scales."""
    from matplotlib.colors import LinearSegmentedColormap
    return LinearSegmentedColormap.from_list(
        "pq_sequential", ["#ffffff", "#c9d0dd", NAVY])


def annotate_cells(ax, values, fmt="%.2f", threshold=0.78, size=6.2):
    # 0.78, not 0.55: mid-tone cells (a 0.55-0.75 correlation) are still light
    # enough that white ink on them is hard to read at 6pt on paper.
    """Write each cell's value, flipping to white ink on dark grounds."""
    import numpy as _np
    v = _np.asarray(values, dtype=float)
    lo, hi = v.min(), v.max()
    for i in range(v.shape[0]):
        for j in range(v.shape[1]):
            norm = (v[i, j] - lo) / (hi - lo) if hi > lo else 0.0
            ax.text(j, i, fmt % v[i, j], ha="center", va="center",
                    fontsize=size,
                    color="white" if norm > threshold else INK)
