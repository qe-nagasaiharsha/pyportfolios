SERIES = [NAVY, OCHRE, SLATE, CLAY]

# The notes set figures at the full 532.8bp measure = 7.4in, so a 7.4in-wide
# figure maps 1:1 onto the page and chart point sizes equal page point sizes.
WIDTH = 7.4
DPI = 200

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
DATA_DIR = os.path.join(REPO, "site", "src", "content", "articles", "data")


def _register_fonts():
    base = os.path.join(os.environ.get("APPDATA", ""), "MiKTeX", "fonts",
                        "opentype", "public", "tex-gyre")
    for name in ("texgyreheros-regular.otf", "texgyreheros-bold.otf",
                 "texgyreheros-italic.otf"):
        p = os.path.join(base, name)
        if os.path.exists(p):
            font_manager.fontManager.addfont(p)


_register_fonts()

