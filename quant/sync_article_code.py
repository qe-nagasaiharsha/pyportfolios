# =============================================================================
# Lift the code blocks an article displays straight out of its notebook.
#
# The article pages used to carry their own hand-typed copies of the code. That
# is how a page ends up showing code the download does not contain — the exact
# complaint from September. Here the notebook is the single source: its code
# cells become the `export const` strings the .tsx imports, verbatim.
#
# Run:  python quant/sync_article_code.py
# =============================================================================

import io
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DOWNLOADS = os.path.join(os.path.expanduser("~"), "Downloads")

# article code module  <-  notebook, and what to call each code cell.
# A name of None drops that cell (plot styling the page does not show, since
# the page draws its own charts from the generated data).
JOBS = [
    {
        "notebook": os.path.join(DOWNLOADS, "01-02_T_BlackScholes_v2.ipynb"),
        "out": os.path.join(ROOT, "site", "src", "content", "articles",
                            "black-scholes-greeks-code.ts"),
        "title": "Black-Scholes & the Greeks",
        "source": "01-02_T_BlackScholes_v2",
        "names": [None, "BSM_CODE", "QQQ_CODE", "GREEKS_STRIKES_CODE",
                  "THETA_CODE", "SANITY_CODE"],
    },
    {
        "notebook": os.path.join(DOWNLOADS, "01-03_T_BondDuration_v2.ipynb"),
        "out": os.path.join(ROOT, "site", "src", "content", "articles",
                            "bond-code.ts"),
        "title": "Bond Pricing, Duration & Convexity",
        "source": "01-03_T_BondDuration_v2",
        "names": [None, "BOND_FUNCS", "PRICE_YIELD_CODE", "LADDER_CODE",
                  "ETF_CODE", "TAYLOR_CODE"],
    },
]

HEADER = """/* Code shown in the %(title)s article.

   GENERATED by quant/sync_article_code.py - do not hand-edit.
   Lifted verbatim from the %(source)s notebook, so the code on the page and
   the code in the download cannot drift apart.

   The notebook's matplotlib styling cell is deliberately not included: the
   page draws its own interactive charts from the generated data module. */
"""


def esc(text):
    """Escape a Python source string for a JS template literal."""
    text = text.replace("\\", "\\\\")
    text = text.replace("`", "\\`")
    text = text.replace("${", "\\${")
    return text.rstrip()


def main():
    for job in JOBS:
        with io.open(job["notebook"], encoding="utf-8") as fh:
            nb = json.load(fh)
        cells = ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]
        names = job["names"]
        if len(cells) != len(names):
            raise SystemExit(
                "%s has %d code cells but %d names are mapped — the notebook "
                "changed shape, so the mapping needs revisiting."
                % (os.path.basename(job["notebook"]), len(cells), len(names))
            )

        parts = [HEADER % {"title": job["title"], "source": job["source"]}]
        kept = 0
        for name, cell in zip(names, cells):
            if name is None:
                continue
            kept += 1
            parts.append("export const %s = `%s`;\n" % (name, esc(cell)))

        with io.open(job["out"], "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(parts))
        print("  %-28s %d of %d cells" % (os.path.relpath(job["out"], ROOT), kept, len(cells)))


if __name__ == "__main__":
    main()
